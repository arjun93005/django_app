"""EXPLAIN (ANALYZE, BUFFERS) the hot queries of the system.

Write paths (frontier claim, change-detection insert) are executed inside a
transaction that is rolled back - EXPLAIN ANALYZE really runs the statement.

    python manage.py seed_demo_data
    python manage.py explain_queries --out docs/query-plans.md
"""

from datetime import timedelta

from django.core.management.base import BaseCommand
from django.db import connection, transaction
from django.utils import timezone

from apps.analytics.services import PRICE_DROPS_SQL
from apps.catalog.models import PricePoint, Product
from apps.catalog.search import WORD_SIMILARITY_THRESHOLD
from apps.crawler.frontier import CLAIM_SQL
from apps.crawler.models import Source
from apps.crawler.pipeline import INSERT_PRICE_CHANGES_SQL

OPTIONS = "ANALYZE, BUFFERS, COSTS OFF, TIMING ON, SUMMARY ON"


class Rollback(Exception):
    pass


class Command(BaseCommand):
    help = "Print EXPLAIN ANALYZE plans for the performance-critical queries."

    def add_arguments(self, parser):
        parser.add_argument("--out", help="also write the report (markdown) to this file")

    def explain_sql(self, sql: str, params) -> str:
        try:
            with transaction.atomic(), connection.cursor() as cursor:
                cursor.execute(f"EXPLAIN ({OPTIONS}) {sql}", params)
                plan = "\n".join(row[0] for row in cursor.fetchall())
                raise Rollback
        except Rollback:
            return plan

    def explain_qs(self, queryset) -> str:
        return queryset.explain(analyze=True, buffers=True, costs=False)

    def handle(self, *args, **opts):
        source = Source.objects.filter(slug="synthetic").first() or Source.objects.first()
        product_ids = list(Product.objects.filter(source=source).values_list("id", flat=True)[:200])
        if not product_ids:
            self.stderr.write("no data - run `manage.py seed_demo_data` first")
            return
        sample = Product.objects.get(pk=product_ids[0])
        week_ago = timezone.now() - timedelta(days=7)
        counts = {
            "products": Product.objects.count(),
            "price points": PricePoint.objects.count(),
        }

        sections: list[tuple[str, str, str]] = [
            (
                "Frontier claim - FOR UPDATE SKIP LOCKED",
                "Partial index `frontier_claim_idx` (status = 'pending') is walked in priority order; "
                "rows locked by other workers are skipped instead of waited for.",
                self.explain_sql(CLAIM_SQL, {"source_id": source.pk, "limit": 10, "worker": "explain"}),
            ),
            (
                "Latest price of one product",
                "Backward index-only scan on `pricepoint_product_latest` (INCLUDE price): no heap access.",
                self.explain_sql(
                    "SELECT price FROM catalog_pricepoint WHERE product_id = %s ORDER BY observed_at DESC LIMIT 1",
                    [sample.pk],
                ),
            ),
            (
                "Change-detection insert (200 items, LATERAL)",
                "One LATERAL index probe per incoming item; only changed prices are inserted.",
                self.explain_sql(
                    INSERT_PRICE_CHANGES_SQL,
                    {
                        "now": timezone.now(),
                        "run_id": None,
                        "product_ids": product_ids,
                        "prices": [p.current_price for p in Product.objects.filter(pk__in=product_ids).order_by("pk")],
                        "currencies": ["USD"] * len(product_ids),
                        "in_stocks": [True] * len(product_ids),
                    },
                ),
            ),
            (
                "Product list API page (cursor pagination + previous price subquery)",
                "Generated by the ORM; ORDER BY id DESC LIMIT 51 walks the primary key backwards.",
                self.explain_qs(
                    Product.objects.select_related("source", "category")
                    .only("id", "title", "current_price", "source__slug", "category__slug")
                    .with_previous_price()
                    .filter(category__isnull=False)
                    .order_by("-id")[:51]
                ),
            ),
            (
                "Full-text search",
                "Bitmap index scan on the GIN `product_search_gin` index.",
                self._explain_search(),
            ),
            (
                "Typo-tolerant search (pg_trgm word similarity)",
                "`%>` operator lets the planner use the gin_trgm_ops index.",
                self._explain_trigram(),
            ),
            (
                "Biggest price drops (BRIN range + LATERAL previous-price probe)",
                "Recent rows come from the BRIN index; each one's predecessor is a single index-only probe. "
                "(A first version computed lag() over every product's full history: 585 ms on this dataset.)",
                self.explain_sql(
                    PRICE_DROPS_SQL, {"since": week_ago, "min_drop_pct": 10, "category": None, "limit": 50}
                ),
            ),
            (
                "7-day time range aggregate (BRIN)",
                "BRIN on observed_at prunes block ranges outside the window; the index is a few kB.",
                self.explain_sql(
                    "SELECT count(*), avg(price) FROM catalog_pricepoint WHERE observed_at >= %s", [week_ago]
                ),
            ),
        ]

        lines = ["# Query plans", "", f"Dataset: {counts}", ""]
        for title, note, plan in sections:
            lines += [f"## {title}", "", note, "", "```", plan, "```", ""]
        report = "\n".join(lines)
        self.stdout.write(report)
        if opts["out"]:
            with open(opts["out"], "w", encoding="utf-8", newline="\n") as fh:
                fh.write(report)

    def _explain_search(self) -> str:
        from django.contrib.postgres.search import SearchQuery, SearchRank
        from django.db.models import F

        query = SearchQuery("wireless headphones", search_type="websearch", config="english")
        qs = (
            Product.objects.filter(search_vector=query)
            .annotate(rank=SearchRank(F("search_vector"), query))
            .order_by("-rank")[:50]
        )
        return self.explain_qs(qs)

    def _explain_trigram(self) -> str:
        from django.contrib.postgres.search import TrigramWordSimilarity

        with transaction.atomic(), connection.cursor() as cursor:
            cursor.execute(
                "SELECT set_config('pg_trgm.word_similarity_threshold', %s, true)", [str(WORD_SIMILARITY_THRESHOLD)]
            )
            qs = (
                Product.objects.filter(title__trigram_word_similar="keybaord")
                .annotate(rank=TrigramWordSimilarity("keybaord", "title"))
                .order_by("-rank")[:50]
            )
            return self.explain_qs(qs)
